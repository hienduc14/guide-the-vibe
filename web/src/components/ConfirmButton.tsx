import { useEffect, useState, type ReactNode } from "react";

/** Two-step button for destructive actions: first click arms, second click runs. */
export function ConfirmButton({
  onConfirm,
  children,
  confirmLabel = "Chắc chắn?",
  className = "btn sm danger",
}: {
  onConfirm: () => void;
  children: ReactNode;
  confirmLabel?: string;
  className?: string;
}) {
  const [armed, setArmed] = useState(false);
  useEffect(() => {
    if (!armed) return;
    const t = window.setTimeout(() => setArmed(false), 3000);
    return () => window.clearTimeout(t);
  }, [armed]);
  return (
    <button
      type="button"
      className={className}
      onClick={() => {
        if (armed) {
          setArmed(false);
          onConfirm();
        } else setArmed(true);
      }}
    >
      {armed ? confirmLabel : children}
    </button>
  );
}
